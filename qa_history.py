
"""
EditorialDesk — Question and Answer History
==========================================

This module manages the persistent storage of questions
and answers generated by the EditorialDesk RAG application.

The purpose is to maintain a readable local archive of
user interactions, including retrieved document references.

Main Features
-------------
1. Record user questions and assistant responses.
2. Attach timestamps to each interaction.
3. Record whether an answer was AI-generated or retrieved.
4. Store source document names and similarity scores.
5. Automatically create the history directory if needed.
6. Append new interactions without deleting previous ones.

Storage Format
--------------
All interactions are saved in a UTF-8 plain-text file:

    history/questions_and_answers.txt

The history directory is deliberately located outside
the knowledge/ directory.

This separation prevents saved conversations from being
retrieved as editorial policy documents.

Functions
---------
format_record(question, reply, matches, mode, when):
    Convert a question-answer exchange into readable text.

save_record(question, reply, matches, mode, path):
    Append the formatted exchange to the history file.

Dependencies
------------
datetime:
    Provides timestamps for recorded interactions.

pathlib:
    Handles file paths and directory creation.

Privacy
-------
The history file is stored locally on the computer
running the Streamlit application.

It may contain user questions and generated answers,
so it should not be committed to a public GitHub
repository if it contains private information.
"""

from datetime import datetime
from pathlib import Path


# ---------------------------------------------------------
# 1. HISTORY FILE CONFIGURATION
# ---------------------------------------------------------

# Resolve the directory containing this Python script.
#
# __file__ refers to qa_history.py.
# resolve() produces an absolute file path.
# parent selects the directory containing the file.
#
# The history file is stored at:
#
# editorialdesk-mini-rag/
# ├── app.py
# ├── rag.py
# ├── qa_history.py
# ├── knowledge/
# └── history/
#     └── questions_and_answers.txt

HISTORY_FILE = (
    Path(__file__).resolve().parent
    / "history"
    / "questions_and_answers.txt"
)


# ---------------------------------------------------------
# 2. FORMAT QUESTION-AND-ANSWER RECORD
# ---------------------------------------------------------

def format_record(
    question: str,
    reply: str,
    matches=(),
    mode: str = "AI-generated",
    when=None
) -> str:
    """
    Format one question-and-answer exchange as plain text.

    This function creates a human-readable record containing
    the timestamp, response mode, user question, assistant
    response, and optional retrieval source information.

    It only constructs a string. It does not write to a file.

    Parameters
    ----------
    question : str
        The natural-language question submitted by the user.

    reply : str
        The answer returned by the RAG application.

        This may contain an AI-generated answer, a retrieval
        preview, or a fallback message.

    matches : iterable, optional
        Retrieved document passages and similarity scores.

        Each match should contain:

            (passage, similarity_score)

        The passage object must provide:
            - heading
            - source

        The similarity score must support float formatting.

        Default is an empty tuple.

    mode : str, optional
        Describes how the response was produced.

        Examples:
            - "AI-generated"
            - "Retrieval preview (no API key)"
            - "No relevant documents found"

        Default is "AI-generated".

    when : datetime, optional
        Timestamp associated with the exchange.

        If omitted or None, the current local date and
        time are used.

        Passing a fixed datetime is useful for testing.

    Returns
    -------
    str
        A formatted text representation of the exchange.

    Notes
    -----
    - Leading and trailing whitespace is removed from
      the question and reply.
    - Retrieved source names and similarity scores are
      included when matches are available.
    - Records are separated using lines of equal signs.
    - This function does not save the record to disk.

    Examples
    --------
    >>> record = format_record(
    ...     question="Can AI drafts be published?",
    ...     reply="Human editorial review is required.",
    ...     mode="AI-generated"
    ... )
    >>> "QUESTION" in record
    True
    >>> "ANSWER" in record
    True
    """

    # Use the supplied timestamp if available.
    # Otherwise, obtain the current local time.

    timestamp = when or datetime.now().astimezone()

    # Create the main record structure.
    #
    # Each list item represents a line in the output.

    lines = [
        "=" * 72,

        f"Date: {timestamp.strftime('%Y-%m-%d %H:%M:%S %Z')}",

        f"Response mode: {mode}",

        "",

        "QUESTION",
        question.strip(),

        "",

        "ANSWER",
        reply.strip(),
    ]

    # -----------------------------------------------------
    # 3. ADD RETRIEVED SOURCE INFORMATION
    # -----------------------------------------------------

    # If the retrieval engine found relevant passages,
    # include their names and similarity scores.
    #
    # enumerate(matches, 1) assigns source numbers:
    #
    # [1], [2], [3], ...
    #
    # These correspond to the references shown by the
    # RAG application.

    if matches:

        lines.extend([
            "",
            "RETRIEVED SOURCES"
        ])

        for i, (passage, score) in enumerate(matches, 1):

            lines.append(
                f"[{i}] {passage.heading} — "
                f"{passage.source} "
                f"(similarity: {score:.2f})"
            )

    # Add a closing separator and two blank lines
    # to distinguish this record from the next.

    lines.extend([
        "=" * 72,
        "",
        ""
    ])

    # Join the list into one multiline string.
    #
    # "\n" represents a new line.

    return "\n".join(lines)


# ---------------------------------------------------------
# 4. SAVE QUESTION-AND-ANSWER RECORD
# ---------------------------------------------------------

def save_record(
    question: str,
    reply: str,
    matches=(),
    mode: str = "AI-generated",
    path: Path = HISTORY_FILE
) -> Path:
    """
    Append a completed question-and-answer exchange to disk.

    This function formats the exchange using format_record()
    and writes it to a UTF-8 text file.

    Existing records are preserved.

    If the destination directory does not exist,
    it is created automatically.

    Parameters
    ----------
    question : str
        The user's submitted question.

    reply : str
        The assistant's response.

    matches : iterable, optional
        Retrieved document passages and relevance scores.

        Default is an empty tuple.

    mode : str, optional
        Identifies the response mode.

        Default is "AI-generated".

    path : pathlib.Path, optional
        Destination file for the saved conversation.

        Default is HISTORY_FILE.

    Returns
    -------
    pathlib.Path
        The path of the file where the record was saved.

    Raises
    ------
    OSError
        If the directory cannot be created or the file
        cannot be opened or written.

    Notes
    -----
    The file is opened using append mode ("a").

    This means:
        - Existing records remain unchanged.
        - New records are added to the end.
        - The file is created if it does not exist.

    UTF-8 encoding supports international characters.

    Examples
    --------
    >>> from pathlib import Path
    >>> from tempfile import TemporaryDirectory
    >>> with TemporaryDirectory() as folder:
    ...     output = save_record(
    ...         question="What is RAG?",
    ...         reply="Retrieval-Augmented Generation.",
    ...         path=Path(folder) / "history.txt"
    ...     )
    ...     print(output.is_file())
    True
    """

    # Convert the destination to a Path object.
    #
    # This allows callers to provide either a string
    # or an existing pathlib.Path object.

    path = Path(path)

    # Create the parent directory if it does not exist.
    #
    # parents=True:
    #     Create missing parent directories as needed.
    #
    # exist_ok=True:
    #     Do not raise an error if the directory exists.

    path.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    # Open the history document in append mode.
    #
    # "a":
    #     Append new content instead of overwriting.
    #
    # encoding="utf-8":
    #     Support international characters.
    #
    # newline="\n":
    #     Use consistent line endings.

    with path.open(
        "a",
        encoding="utf-8",
        newline="\n"
    ) as file:

        # Convert the exchange into formatted text
        # and append it to the history file.

        file.write(
            format_record(
                question,
                reply,
                matches,
                mode
            )
        )

    # Return the path for use by other modules.

    return path
